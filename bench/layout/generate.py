#!/usr/bin/env python3
"""Write the linker script that keeps what a serving worker uses side by side.
Called by regen.sh.

  generate.py OUT.ld --trace FILE... [--data FILE] [--strings FILE] [--probe] --archives LIB.a...

--trace    functions in first-call order, one "name<TAB>size" per line.
--data     constants to place ahead of .rodata / inside .data.rel.ro: "name<TAB>section".
--strings  archive members whose string literals go ahead of .rodata (literals
           cannot be placed one by one); "-" stands for the objects outside the archives.
--archives the static libraries of the link. A traced function without a
           section of its own there (assembly) pulls in its object's .text.
--probe    measuring layout: every constant starts on a page of its own and every
           member's literals get a page-aligned section .rodata.lit.N (N is the line
           in OUT.ld.members), so page residency tells exactly which are read.
"""
import argparse, re, subprocess

OWN = '-'  # the objects of the link that are in no archive

def pattern(section):
    section = re.sub(r'__anon_\d+', '__anon_*', section)
    return re.sub(r'[^A-Za-z0-9_.$*-]', '?', section)

def archive_symbols(archives):
    """(symbol -> (member, section), members) of the archives."""
    found, members = {}, []
    for archive in archives:
        member = None
        text = subprocess.run(['objdump', '-t', archive], capture_output=True, text=True, check=True).stdout
        for line in text.splitlines():
            if ':     file format ' in line:
                member = line.split(':', 1)[0]; members.append(member)
                continue
            f = line.split()
            if len(f) >= 6 and f[-3].startswith(('.text', '.rodata', '.data.rel.ro')):
                found.setdefault(f[-1], (member, f[-3]))
    return found, members

def main():
    p = argparse.ArgumentParser()
    p.add_argument('out'); p.add_argument('--trace', nargs='+', required=True)
    p.add_argument('--data'); p.add_argument('--strings'); p.add_argument('--probe', action='store_true')
    p.add_argument('--archives', nargs='+', required=True)
    a = p.parse_args()
    known, members = archive_symbols(a.archives)
    text, seen = [], set()
    for trace in a.trace:
        for line in open(trace):
            name = line.split('\t')[0]
            member, section = known.get(name, (None, '.text.' + name))
            entry = f'*{member}(.text)' if section == '.text' else f'*({pattern(section)})'
            if entry not in seen:
                seen.add(entry); text.append(entry)
    ro, relro = [], []
    for line in open(a.data) if a.data else ():
        name, section = line.rstrip('\n').split('\t')[:2]
        section = section.removesuffix('.hot')
        member, input_section = known.get(name, (None, section + '.' + name))
        # Zig numbers its anonymous constants per build; they cannot be named here.
        if '__anon_' in name or '.str' in input_section or '.cst' in input_section or input_section == '.data.rel.ro':
            continue
        entry = f'*{member}(.rodata)' if input_section == '.rodata' else f'*({pattern(input_section)})'
        if entry not in seen:
            seen.add(entry)
            (relro if input_section.startswith('.data.rel.ro') else ro).append(entry)
    if a.strings:
        members = [line.strip() for line in open(a.strings) if line.strip()]
    else:
        members = [OWN] + members if a.probe else []
    def literals(member):
        files = '*(EXCLUDE_FILE(*.a:*) ' if member == OWN else f'*{member}('
        return files + '.rodata.str* .rodata.cst*)'
    page = '    . = ALIGN(4096);\n' if a.probe else ''
    with open(a.out, 'w') as o:
        o.write('/* Generated by bench/layout/regen.sh: code and constants a serving worker uses,\n'
                ' * placed side by side so they share pages. Do not edit by hand. */\n')
        if text:
            o.write('SECTIONS {\n  .text.hot : {\n%s  }\n} INSERT BEFORE .text;\n' % ''.join('    %s\n' % e for e in text))
        if a.probe:
            # The linker merges the literals of one output section into one blob,
            # so telling the members apart takes a section each.
            ro.append('BYTE(0)')
            for i, member in enumerate(members):
                o.write('SECTIONS { .rodata.lit.%d : ALIGN(4096) { %s } } INSERT BEFORE .rodata;\n' % (i, literals(member)))
        else:
            ro += [literals(member) for member in members]
        if ro:
            o.write('SECTIONS {\n  .rodata.hot : ALIGN(4096) {\n')
            o.writelines('%s    %s\n' % (page, e) for e in ro)
            o.write('%s  }\n} INSERT BEFORE .rodata;\n' % page)
        if relro:
            # lld only treats a section named .data.rel.ro as RELRO, so that one is
            # redefined in full instead of getting a sibling.
            o.write('SECTIONS {\n  .data.rel.ro : {\n')
            o.writelines('%s    %s\n' % (page, e) for e in relro)
            o.write('%s    *(.data.rel.ro .data.rel.ro.*)\n  }\n} INSERT BEFORE .dynamic;\n' % page)
    if a.probe:
        with open(a.out + '.members', 'w') as o:
            o.writelines(m + '\n' for m in members)
    print(f'{a.out}: {len(text)} code, {len(ro)} rodata, {len(relro)} relro entries, literals of {len(members)} members')

main()
